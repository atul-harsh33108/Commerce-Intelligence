-- The transactional outbox.
--
-- THE PROBLEM IT SOLVES, precisely.
--
-- Placing an order is two writes to two different systems: a row in Postgres and a record in Kafka.
-- There is no transaction that spans both. So the naive code -
--
--     @Transactional
--     void place(...) {
--         orders.save(order);              // committed at method exit
--         kafka.send("order.placed", ...);  // a separate, unrelated act
--     }
--
-- - has a window between the commit and the send in which the process can die. When it does, the
-- order exists and NOTHING DOWNSTREAM WILL EVER HEAR ABOUT IT. No stock is reserved, no payment is
-- taken, no email is sent, and no error is logged anywhere, because from the database's point of
-- view the transaction succeeded. The customer sees a confirmed order that never happens.
--
-- Sending BEFORE the commit is worse: now a rolled-back transaction has already announced an order
-- that does not exist, and consumers reserve stock for it forever.
--
-- The outbox makes the two writes one write. The event row is inserted in the SAME transaction as
-- the order, so either both are durable or neither is. A separate relay then reads unpublished rows
-- and sends them to Kafka, marking them published afterwards. If the relay dies mid-send, the row is
-- still unpublished and it sends again - at-least-once, which consumers already have to handle
-- (see inventory-service's processed_events).
--
-- What it does NOT give you: exactly-once, or ordering across aggregates. It converts "the event may
-- be lost" into "the event may be duplicated", and duplication is solvable.

CREATE TABLE outbox_events
(
    -- The event's identity, generated by the producer and carried into Kafka as a header.
    -- Consumers deduplicate on THIS, not on a Kafka offset or a per-message id: the same row
    -- republished after a relay restart keeps the same event_id, so the redelivery is recognisable.
    event_id       UUID PRIMARY KEY,

    -- Which aggregate this is about. `aggregate_id` becomes the Kafka message key, which is what
    -- puts every event about one order on one partition - and partition order is the only ordering
    -- Kafka guarantees. Publishing with a null key round-robins, and then "order placed" and "order
    -- cancelled" can be processed by different threads in either order.
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(64)  NOT NULL,

    event_type     VARCHAR(80)  NOT NULL,
    topic          VARCHAR(120) NOT NULL,

    -- JSONB, not TEXT. The payload is opaque to the relay - it neither parses nor validates it - but
    -- jsonb makes it queryable when something goes wrong, which is exactly when somebody needs to
    -- ask "what did we publish for order X?" without writing a parser.
    payload        JSONB        NOT NULL,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- NULL means unpublished. A nullable timestamp rather than a boolean + timestamp pair, because
    -- two columns that must agree are two columns that can disagree.
    published_at   TIMESTAMPTZ,

    -- Bookkeeping for the failure path: how many times the relay has tried, and what went wrong.
    -- Without these a permanently-failing row is invisible - the relay just keeps quietly retrying.
    attempts       INTEGER      NOT NULL DEFAULT 0,
    last_error     VARCHAR(500)
);

-- THE INDEX THE RELAY LIVES ON.
--
-- PARTIAL, on `published_at IS NULL`. The outbox is append-only and grows to the size of every event
-- ever emitted, while the relay's query only ever asks about the handful that are not yet published.
-- A full index on published_at would be millions of entries to answer a question about five of them;
-- this one stays approximately empty, because a row leaves the index as soon as it is published.
--
-- Ordered by created_at so the relay drains oldest-first, which keeps per-aggregate ordering intact
-- as long as one relay pass covers them.
CREATE INDEX idx_outbox_unpublished ON outbox_events (created_at)
    WHERE published_at IS NULL;

-- For "what happened to order X", and for the retention job that will eventually delete published
-- rows older than N days. That job is deliberately not written here: the right retention depends on
-- how long a consumer might need to replay, which is a deployment decision.
CREATE INDEX idx_outbox_aggregate ON outbox_events (aggregate_type, aggregate_id, created_at);


-- Saga state on the order itself.
--
-- A separate `saga_state` table was the alternative and is rejected: the saga's state IS the order's
-- state (PENDING -> AWAITING_PAYMENT -> CONFIRMED / CANCELED), and duplicating it into a second
-- table creates two answers to "what happened to this order" that can disagree. What the order row
-- did not have is a record of WHEN each step completed, which is what makes the recovery job able to
-- distinguish "waiting" from "stuck".
ALTER TABLE orders ADD COLUMN reserved_at   TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN paid_at       TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN compensated_at TIMESTAMPTZ;
